// renderConceptPage builds one concept guide from its markdown source or the
// inline catalog sections when no source document exists.
// parseConceptSlugsByDoc maps a doc filename (e.g. "logging.md") to its
// concept page slug so doc-to-doc links resolve to sibling pages.
func renderConceptPage(parseConcept catalogItem, parseMarkdown string, parseConceptSlugsByDoc map[string]string) ui.Node {
	parseChrome := pageChrome{
		Title:       parseConcept.Title + " — GoWebComponents",
		Description: parseConcept.Blurb,
		RootPrefix:  "../../..",
		ActiveNav:   "learn",
	}

	var parseBody []ui.Node
	if parseMarkdown != "" {
		parseBody = gwchtml.RenderMarkdown(parseMarkdown, gwchtml.MarkdownRenderOptions{
			SourcePath: parseConcept.Content.SourcePath,
			Classes:    markdownProseClasses,
			ResolveHref: func(parseSourcePath, parseDestination string) string {
				return resolveConceptHref(parseDestination, parseConceptSlugsByDoc)
			},
		})
	} else {
		parseBody = append(parseBody, H1(Text(parseConcept.Title)))
		for _, parseSection := range parseConcept.Content.Sections {
			if parseSection.Heading != "" {
				parseBody = append(parseBody, H2(Text(parseSection.Heading)))
			}
			for _, parseParagraph := range parseSection.Paragraphs {
				parseBody = append(parseBody, P(Text(parseParagraph)))
			}
		}
	}

	return renderPage(parseChrome,
		Main(Class("container"),
			Article(append([]interface{}{Class("prose"), Style(map[string]string{"padding-top": "40px"})}, nodesToArgs(parseBody)...)...),
		),
	)
}

// resolveConceptHref rewrites concept-doc markdown links: sibling doc links
// become concept pages, everything else repo-relative goes to GitHub.
func resolveConceptHref(parseDestination string, parseConceptSlugsByDoc map[string]string) string {
	parseTrimmed := strings.TrimSpace(parseDestination)
	if parseTrimmed == "" || strings.HasPrefix(parseTrimmed, "http") || strings.HasPrefix(parseTrimmed, "#") {
		return parseTrimmed
	}
	parseBase, parseFragment, _ := strings.Cut(parseTrimmed, "#")
	if strings.HasSuffix(parseBase, ".md") {
		parseDocName := path.Base(parseBase)
		if parseSlug, isParseKnown := parseConceptSlugsByDoc[parseDocName]; isParseKnown {
			parseResolved := "../" + parseSlug + "/index.html"
			if parseFragment != "" {
				parseResolved += "#" + parseFragment
			}
			return parseResolved
		}
	}
	parseRepoPath := path.Clean(path.Join("examples/public-examples-site/assets/docs", parseBase))
	parseResolved := "https://github.com/monstercameron/GoWebComponents/blob/master/" + parseRepoPath
	if parseFragment != "" {
		parseResolved += "#" + parseFragment
	}
	return parseResolved
}

// renderExamplesGallery builds the filterable example gallery.
func renderExamplesGallery(parseExamples []catalogItem) ui.Node {
	parseChrome := pageChrome{
		Title:       "Examples — GoWebComponents",
		Description: "Live, runnable examples for every framework feature, each with mirrored Go source.",
		RootPrefix:  "..",
		ActiveNav:   "examples",
	}

	parseModuleSet := map[string]bool{}
	for _, parseExample := range parseExamples {
		parseModuleSet[parseExample.Module] = true
	}
	parseFilterChips := []interface{}{Class("filter-bar"),
		Button(Class("filter-chip"), Attr("type", "button"), Attr("data-filter", "all"), Attr("data-active", "true"), Text("All"))}
	for _, parseModule := range sortedKeys(parseModuleSet) {
		parseFilterChips = append(parseFilterChips,
			Button(Class("filter-chip"), Attr("type", "button"), Attr("data-filter", parseModule), Text(parseModule)))
	}

	parseCards := []interface{}{Class("card-grid")}
	for _, parseExample := range parseExamples {
		parseActions := []interface{}{Class("card-actions")}
		if parseExample.Content.PreviewPath != "" {
			parseActions = append(parseActions,
				A(Href("../public-examples-site/"+parseExample.Content.PreviewPath), Attr("target", "_blank"), Text("Run live →")))
		}
		if parseExample.Content.SourcePath != "" {
			parseActions = append(parseActions,
				A(Href("../public-examples-site/"+parseExample.Content.SourcePath), Attr("target", "_blank"), Text("Source")))
		}
		parseCards = append(parseCards, Div(Class("catalog-card"), Attr("data-module", parseExample.Module),
			H3(Text(parseExample.Title)),
			P(Text(parseExample.Blurb)),
			Div(Class("card-meta"),
				Span(Class("chip chip-level"), Text(parseExample.Level)),
				Span(Class("chip"), Text(parseExample.Module)),
			),
			Div(parseActions...),
		))
	}

	return renderPage(parseChrome,
		Main(Class("container"),
			H1(Class("page-title"), Textf("%d live examples", len(parseExamples))),
			P(Class("page-sub"), Text("Every example runs real wasm in your browser and ships with its mirrored Go source. Filter by subsystem, run anything, copy everything.")),
			Div(parseFilterChips...),
			Div(parseCards...),
		),
	)
}

