// markdownProseClasses maps markdown output onto the site design system. The
// prose container styles semantic tags, so only code labels need classes.
var markdownProseClasses = gwchtml.MarkdownClasses{}

// renderChapterPage builds one reference-manual chapter page.
func renderChapterPage(parseChapters []chapter, parseIndex int) ui.Node {
	parseChapter := parseChapters[parseIndex]
	parseChrome := pageChrome{
		Title:       parseChapter.Title + " — GoWebComponents",
		Description: parseChapter.Summary,
		RootPrefix:  "../..",
		ActiveNav:   "learn",
	}

	parseBody := gwchtml.RenderMarkdown(parseChapter.Markdown, gwchtml.MarkdownRenderOptions{
		SourcePath: parseChapter.Slug + ".md",
		Classes:    markdownProseClasses,
		ResolveHref: func(parseSourcePath, parseDestination string) string {
			return resolveChapterHref(parseDestination)
		},
	})

	var parsePagerNodes []ui.Node
	if parseIndex > 0 {
		parsePrevious := parseChapters[parseIndex-1]
		parsePagerNodes = append(parsePagerNodes, A(Href("../"+parsePrevious.Slug+"/index.html"),
			Span(Class("pager-label"), Text("Previous")), Text(parsePrevious.Title)))
	} else {
		parsePagerNodes = append(parsePagerNodes, Span())
	}
	if parseIndex < len(parseChapters)-1 {
		parseNext := parseChapters[parseIndex+1]
		parsePagerNodes = append(parsePagerNodes, A(Class("pager-next"), Href("../"+parseNext.Slug+"/index.html"),
			Span(Class("pager-label"), Text("Next")), Text(parseNext.Title)))
	}

	return renderPage(parseChrome,
		Main(Class("container"),
			Div(Class("learn-layout"),
				renderLearnSidebar(parseChapters, parseChapter.Slug, ".."),
				Div(
					Article(append([]interface{}{Class("prose")}, nodesToArgs(parseBody)...)...),
					Div(Class("chapter-pager"), parsePagerNodes[0], parsePagerNodes[len(parsePagerNodes)-1]),
				),
			),
		),
	)
}

// resolveChapterHref rewrites chapter-to-chapter markdown links to site URLs.
func resolveChapterHref(parseDestination string) string {
	parseTrimmed := strings.TrimSpace(parseDestination)
	if strings.HasPrefix(parseTrimmed, "http") || strings.HasPrefix(parseTrimmed, "#") {
		return parseTrimmed
	}
	parseBase, parseFragment, _ := strings.Cut(parseTrimmed, "#")
	if strings.HasSuffix(parseBase, ".md") && !strings.Contains(parseBase, "/") {
		parseSlug := strings.TrimSuffix(strings.TrimPrefix(parseBase, "./"), ".md")
		parseResolved := "../" + parseSlug + "/index.html"
		if parseFragment != "" {
			parseResolved += "#" + parseFragment
		}
		return parseResolved
	}
	// Repo-relative links (source files, example dirs, other docs) cannot be
	// served from the static site; send them to the repository instead.
	parseRepoPath := path.Clean(path.Join("docs/REFERENCE_MANUAL", parseBase))
	parseResolved := "https://github.com/monstercameron/GoWebComponents/blob/master/" + parseRepoPath
	if parseFragment != "" {
		parseResolved += "#" + parseFragment
	}
	return parseResolved
}

// renderLearnSidebar lists every chapter with the active one highlighted.
func renderLearnSidebar(parseChapters []chapter, parseActiveSlug string, parseLearnPrefix string) ui.Node {
	parseLinks := []interface{}{Class("learn-sidebar"),
		Div(Class("sidebar-group"), Text("Reference manual"))}
	for _, parseChapter := range parseChapters {
		parseAttrs := []interface{}{Href(parseLearnPrefix + "/" + parseChapter.Slug + "/index.html"), Text(chapterShortTitle(parseChapter))}
		if parseChapter.Slug == parseActiveSlug {
			parseAttrs = append(parseAttrs, Attr("data-active", "true"))
		}
		parseLinks = append(parseLinks, A(parseAttrs...))
	}
	return Aside(parseLinks...)
}

// chapterShortTitle strips numeric prefixes for sidebar display.
func chapterShortTitle(parseChapter chapter) string {
	parseTitle := parseChapter.Title
	if parseCut := strings.Index(parseTitle, ": "); parseCut > 0 && parseCut < 14 {
		parseTitle = parseTitle[parseCut+2:]
	}
	return parseTitle
}

