package benchmarks

import (
	"encoding/json"
	"fmt"
	"math"
	"os"
	"sort"
	"strconv"
	"strings"
)

const driftNoteTopEntryCount = 5

type BenchmarkReport struct {
	OK                 bool                        `json:"ok"`
	Root               string                      `json:"root"`
	GeneratedAt        string                      `json:"generatedAt"`
	GoVersion          string                      `json:"goVersion"`
	GOOS               string                      `json:"goos"`
	GOARCH             string                      `json:"goarch"`
	SelectedLanes      []string                    `json:"selectedLanes"`
	Bench              string                      `json:"bench"`
	Count              int                         `json:"count"`
	PackageParallelism int                         `json:"packageParallelism"`
	ReportPath         string                      `json:"reportPath"`
	PackageCount       int                         `json:"packageCount"`
	BenchmarkCount     int                         `json:"benchmarkCount"`
	FailedPackages     int                         `json:"failedPackages"`
	Scores             *BenchmarkScoreSummary      `json:"scores,omitempty"`
	Comparison         *BenchmarkComparisonSummary `json:"comparison,omitempty"`
}

type BenchmarkScoreSummary struct {
	Method               string                 `json:"method"`
	ReferencePath        string                 `json:"referencePath"`
	ReferenceGeneratedAt string                 `json:"referenceGeneratedAt"`
	ReferenceMachine     string                 `json:"referenceMachine"`
	MatchedBenchmarks    int                    `json:"matchedBenchmarks"`
	OverallScore         float64                `json:"overallScore"`
	Buckets              []BenchmarkBucketScore `json:"buckets"`
}

type BenchmarkBucketScore struct {
	ID                string  `json:"id"`
	Label             string  `json:"label"`
	MatchedBenchmarks int     `json:"matchedBenchmarks"`
	Score             float64 `json:"score"`
}

type BenchmarkComparisonSummary struct {
	BaselineGeneratedAt string                      `json:"baselineGeneratedAt,omitempty"`
	TolerancePct        float64                     `json:"tolerancePct"`
	MatchedMetrics      int                         `json:"matchedMetrics"`
	Improved            int                         `json:"improved"`
	Regressed           int                         `json:"regressed"`
	Unchanged           int                         `json:"unchanged"`
	Entries             []BenchmarkMetricComparison `json:"entries,omitempty"`
}

type BenchmarkMetricComparison struct {
	Lane      string  `json:"lane"`
	Package   string  `json:"package"`
	Benchmark string  `json:"benchmark"`
	Metric    string  `json:"metric"`
	Baseline  float64 `json:"baseline"`
	Current   float64 `json:"current"`
	Delta     float64 `json:"delta"`
	DeltaPct  float64 `json:"deltaPct"`
	Direction string  `json:"direction"`
}

func LoadReport(parsePath string) (BenchmarkReport, error) {
	parseBytes, parseErr := os.ReadFile(parsePath)
	if parseErr != nil {
		return BenchmarkReport{}, parseErr
	}
	var parseReport BenchmarkReport
	if parseErr2 := json.Unmarshal(parseBytes, &parseReport); parseErr2 != nil {
		return BenchmarkReport{}, parseErr2
	}
	return parseReport, nil
}

func RenderDriftNote(parseReport BenchmarkReport) string {
	var parseBuilder strings.Builder
	parseBuilder.WriteString("<!-- Code generated by BENCHMARKS_WRITE=1 go test ./docs/benchmarks; DO NOT EDIT. -->\n\n")
	parseBuilder.WriteString("# Benchmark Drift Note\n\n")
	parseBuilder.WriteString("This note is generated from `docs/benchmarks/latest.json`. CI byte-compares it against the committed file so benchmark-report updates also refresh the published drift status.\n\n")

	parseBuilder.WriteString("## Current Report\n\n")
	fmt.Fprintf(&parseBuilder, "- Generated at: `%s`\n", fallback(parseReport.GeneratedAt, "unknown"))
	fmt.Fprintf(&parseBuilder, "- Toolchain: `%s %s/%s`\n", fallback(parseReport.GoVersion, "unknown"), fallback(parseReport.GOOS, "unknown"), fallback(parseReport.GOARCH, "unknown"))
	fmt.Fprintf(&parseBuilder, "- Report path: `%s`\n", fallback(parseReport.ReportPath, "docs/benchmarks/latest.json"))
	fmt.Fprintf(&parseBuilder, "- Packages / benchmarks: `%d / %d`\n", parseReport.PackageCount, parseReport.BenchmarkCount)
	fmt.Fprintf(&parseBuilder, "- Selected lanes: `%s`\n", strings.Join(parseReport.SelectedLanes, ", "))
	fmt.Fprintf(&parseBuilder, "- Failed packages: `%d`\n\n", parseReport.FailedPackages)

	if parseReport.Scores != nil {
		parseScores := parseReport.Scores
		parseBuilder.WriteString("## Normalized Score\n\n")
		fmt.Fprintf(&parseBuilder, "- Method: `%s`\n", fallback(parseScores.Method, "unknown"))
		fmt.Fprintf(&parseBuilder, "- Reference: `%s` generated at `%s`\n", fallback(parseScores.ReferencePath, "unknown"), fallback(parseScores.ReferenceGeneratedAt, "unknown"))
		fmt.Fprintf(&parseBuilder, "- Matched benchmarks: `%d`\n", parseScores.MatchedBenchmarks)
		fmt.Fprintf(&parseBuilder, "- Overall score: `%s`\n\n", formatFloat(parseScores.OverallScore, 1))
	}

	parseBuilder.WriteString("## Drift Status\n\n")
	if parseReport.Comparison == nil {
		parseBuilder.WriteString("No comparison summary is present in the current benchmark report.\n")
		return parseBuilder.String()
	}

	parseComparison := parseReport.Comparison
	parseStatus := "no drift beyond tolerance"
	if parseComparison.Regressed > 0 {
		parseStatus = "drift beyond tolerance detected"
	} else if parseComparison.Improved > 0 {
		parseStatus = "improvements beyond tolerance detected"
	}
	fmt.Fprintf(&parseBuilder, "- Status: `%s`\n", parseStatus)
	fmt.Fprintf(&parseBuilder, "- Baseline generated at: `%s`\n", fallback(parseComparison.BaselineGeneratedAt, "unknown"))
	fmt.Fprintf(&parseBuilder, "- Tolerance: `%s%%`\n", formatFloat(parseComparison.TolerancePct, 1))
	fmt.Fprintf(&parseBuilder, "- Matched metrics: `%d`\n", parseComparison.MatchedMetrics)
	fmt.Fprintf(&parseBuilder, "- Improved / regressed / unchanged: `%d / %d / %d`\n\n", parseComparison.Improved, parseComparison.Regressed, parseComparison.Unchanged)

	writeEntryTable(&parseBuilder, "Top Regressions", topEntries(parseComparison.Entries, "regressed", driftNoteTopEntryCount))
	writeEntryTable(&parseBuilder, "Top Improvements", topEntries(parseComparison.Entries, "improved", driftNoteTopEntryCount))
	return parseBuilder.String()
}

func writeEntryTable(parseBuilder *strings.Builder, parseTitle string, parseEntries []BenchmarkMetricComparison) {
	if len(parseEntries) == 0 {
		return
	}
	fmt.Fprintf(parseBuilder, "### %s\n\n", parseTitle)
	parseBuilder.WriteString("| Lane | Package | Benchmark | Metric | Baseline | Current | Delta | Delta % |\n")
	parseBuilder.WriteString("| --- | --- | --- | --- | ---: | ---: | ---: | ---: |\n")
	for _, parseEntry := range parseEntries {
		fmt.Fprintf(parseBuilder, "| %s | `%s` | `%s` | `%s` | %s | %s | %s | %s%% |\n",
			escapeMarkdownTable(parseEntry.Lane),
			escapeMarkdownTable(parseEntry.Package),
			escapeMarkdownTable(parseEntry.Benchmark),
			escapeMarkdownTable(parseEntry.Metric),
			formatMetric(parseEntry.Baseline),
			formatMetric(parseEntry.Current),
			formatMetric(parseEntry.Delta),
			formatFloat(parseEntry.DeltaPct, 1))
	}
	parseBuilder.WriteString("\n")
}

func topEntries(parseEntries []BenchmarkMetricComparison, parseDirection string, parseLimit int) []BenchmarkMetricComparison {
	parseFiltered := make([]BenchmarkMetricComparison, 0, parseLimit)
	for _, parseEntry := range parseEntries {
		if parseEntry.Direction == parseDirection {
			parseFiltered = append(parseFiltered, parseEntry)
		}
	}
	sort.Slice(parseFiltered, func(parseI, parseJ int) bool {
		parseLeft := math.Abs(parseFiltered[parseI].DeltaPct)
		parseRight := math.Abs(parseFiltered[parseJ].DeltaPct)
		if parseLeft == parseRight {
			if parseFiltered[parseI].Package == parseFiltered[parseJ].Package {
				if parseFiltered[parseI].Benchmark == parseFiltered[parseJ].Benchmark {
					return parseFiltered[parseI].Metric < parseFiltered[parseJ].Metric
				}
				return parseFiltered[parseI].Benchmark < parseFiltered[parseJ].Benchmark
			}
			return parseFiltered[parseI].Package < parseFiltered[parseJ].Package
		}
		return parseLeft > parseRight
	})
	if len(parseFiltered) > parseLimit {
		return parseFiltered[:parseLimit]
	}
	return parseFiltered
}

func formatMetric(parseValue float64) string {
	parseFormatted := strconv.FormatFloat(parseValue, 'f', 3, 64)
	parseFormatted = strings.TrimRight(parseFormatted, "0")
	parseFormatted = strings.TrimRight(parseFormatted, ".")
	if parseFormatted == "-0" {
		return "0"
	}
	return parseFormatted
}

func formatFloat(parseValue float64, parsePrecision int) string {
	return strconv.FormatFloat(parseValue, 'f', parsePrecision, 64)
}

func fallback(parseValue string, parseFallback string) string {
	if strings.TrimSpace(parseValue) == "" {
		return parseFallback
	}
	return parseValue
}

func escapeMarkdownTable(parseValue string) string {
	parseValue = strings.ReplaceAll(parseValue, "\\", "\\\\")
	return strings.ReplaceAll(parseValue, "|", "\\|")
}
